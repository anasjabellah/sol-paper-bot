import { z } from 'zod';
import { BASE58_ADDRESS_RE, MAX_PAIR_CREATED_SKEW_MS, MOCK_MINT_PREFIX } from './constants';

const finitePositive = z.number().finite().positive();
const finiteNonNeg = z.number().finite().nonnegative();
const nullablePositive = finitePositive.nullable();
const nullableNonNeg = finiteNonNeg.nullable();
const nullableCount = z.number().int().nonnegative().nullable();

export const MarketSourceSchema = z.enum(['mock', 'dexscreener']);

/**
 * One normalized market observation for one token.
 * `null` always means "unavailable / unknown" - it is never used for a genuine zero.
 */
export const MarketObservationSchema = z
  .object({
    mint: z.string().min(1).max(64),
    symbol: z.string().max(32),
    name: z.string().max(128),
    source: MarketSourceSchema,
    /** True when the data is generated by the mock simulator, never live. */
    simulated: z.boolean(),
    /** Epoch ms at which this application fetched/generated the observation. */
    observedAt: z.number().int().positive(),
    priceSol: nullablePositive,
    priceUsd: nullablePositive,
    /** SOL side of the pool (AMM quote reserve). */
    quoteReserveSol: nullableNonNeg,
    /** Token side of the pool (AMM base reserve). */
    baseReserve: nullableNonNeg,
    liquidityUsd: nullableNonNeg,
    volume5mSol: nullableNonNeg,
    volume1hSol: nullableNonNeg,
    buys5m: nullableCount,
    sells5m: nullableCount,
    priceChange5mPct: z.number().finite().min(-100).nullable(),
    priceChange1hPct: z.number().finite().min(-100).nullable(),
    pairCreatedAt: z.number().int().positive().nullable(),
    pairAddress: z.string().max(64).nullable(),
    dexId: z.string().max(32).nullable(),
    url: z.string().max(256).nullable(),
  })
  .superRefine((o, ctx) => {
    if (o.source === 'mock') {
      if (!o.simulated) ctx.addIssue({ code: 'custom', path: ['simulated'], message: 'mock data must be flagged simulated' });
      if (!o.mint.startsWith(MOCK_MINT_PREFIX))
        ctx.addIssue({ code: 'custom', path: ['mint'], message: `mock mints must start with ${MOCK_MINT_PREFIX}` });
    } else {
      if (o.simulated) ctx.addIssue({ code: 'custom', path: ['simulated'], message: 'live data cannot be flagged simulated' });
      if (!BASE58_ADDRESS_RE.test(o.mint))
        ctx.addIssue({ code: 'custom', path: ['mint'], message: 'real token identifiers must be base58 mint addresses' });
    }
    if (o.pairCreatedAt !== null && o.pairCreatedAt > o.observedAt + MAX_PAIR_CREATED_SKEW_MS) {
      ctx.addIssue({ code: 'custom', path: ['pairCreatedAt'], message: 'pair creation time is in the future' });
    }
  });

const StrategyConfigObject = z
  .object({
    minLiquiditySol: finiteNonNeg.max(1_000_000),
    minTxns5m: z.number().int().nonnegative().max(100_000),
    minVolume5mSol: finiteNonNeg.max(1_000_000),
    minPriceChange5mPct: z.number().finite().min(-100).max(10_000),
    maxPriceChange5mPct: z.number().finite().min(-100).max(10_000),
    minBuySellRatio: finiteNonNeg.max(1000),
    requireTokenAge: z.boolean(),
    minTokenAgeMinutes: finiteNonNeg.max(525_600),
    maxTokenAgeMinutes: finitePositive.max(5_256_000),
    maxPriceImpactPct: finitePositive.max(50),
    orderSizeSol: finitePositive.max(1000),
    takeProfitPct: finitePositive.max(10_000),
    stopLossPct: finitePositive.max(100),
    trailingStopPct: finitePositive.max(100),
    maxHoldMinutes: finitePositive.max(525_600),
    exitOnLiquidityDropPct: finitePositive.max(100),
  })
  .strict();

export const StrategyConfigSchema = StrategyConfigObject.refine((c) => c.minPriceChange5mPct <= c.maxPriceChange5mPct, {
    message: 'minPriceChange5mPct must be <= maxPriceChange5mPct',
    path: ['minPriceChange5mPct'],
  })
  .refine((c) => c.minTokenAgeMinutes < c.maxTokenAgeMinutes, {
    message: 'minTokenAgeMinutes must be < maxTokenAgeMinutes',
    path: ['minTokenAgeMinutes'],
  });

export const RiskConfigSchema = z
  .object({
    maxOrderSizeSol: finitePositive.max(10_000),
    maxExposurePerTokenSol: finitePositive.max(10_000),
    maxConcurrentPositions: z.number().int().min(1).max(100),
    maxDailyLossSol: finitePositive.max(1_000_000),
    maxDrawdownPct: finitePositive.max(100),
    maxDataAgeMs: z.number().int().min(1000).max(600_000),
    duplicateWindowMs: z.number().int().min(0).max(3_600_000),
    cooldownMinutesAfterExit: finiteNonNeg.max(10_080),
    autoKillOnDrawdown: z.boolean(),
  })
  .strict();

export const CostConfigSchema = z
  .object({
    tradingFeeBps: finiteNonNeg.max(1000),
    slippageBufferBps: finiteNonNeg.max(5000),
    networkFeeSol: finiteNonNeg.max(1),
  })
  .strict();

/** Partial-update schemas for PUT endpoints (cross-field rules re-checked after merge). */
export const StrategyConfigPatchSchema = StrategyConfigObject.partial().strict();
export const RiskConfigPatchSchema = RiskConfigSchema.partial().strict();

const clientOrderId = z
  .string()
  .min(8)
  .max(80)
  .regex(/^[A-Za-z0-9:_\-.]+$/, 'clientOrderId may only contain letters, digits and : _ - .');

/** Manual order submission. `mode` must literally be "PAPER" - there is no other mode. */
export const OrderRequestSchema = z.discriminatedUnion('side', [
  z
    .object({
      mode: z.literal('PAPER'),
      clientOrderId,
      mint: z.string().min(1).max(64),
      side: z.literal('BUY'),
      type: z.enum(['MARKET', 'LIMIT']).default('MARKET'),
      sizeSol: finitePositive.max(10_000),
      limitPriceSol: finitePositive.optional(),
    })
    .strict(),
  z
    .object({
      mode: z.literal('PAPER'),
      clientOrderId,
      mint: z.string().min(1).max(64),
      side: z.literal('SELL'),
      type: z.enum(['MARKET', 'LIMIT']).default('MARKET'),
      /** Fraction of the open position to sell, (0, 1]. */
      fraction: z.number().finite().gt(0).max(1),
      limitPriceSol: finitePositive.optional(),
    })
    .strict(),
]).superRefine((o, ctx) => {
  if (o.type === 'LIMIT' && o.limitPriceSol === undefined)
    ctx.addIssue({ code: 'custom', path: ['limitPriceSol'], message: 'limitPriceSol is required for LIMIT orders' });
  if (o.type === 'MARKET' && o.limitPriceSol !== undefined)
    ctx.addIssue({ code: 'custom', path: ['limitPriceSol'], message: 'limitPriceSol is only valid for LIMIT orders' });
});

export const EmergencyStopSchema = z.object({ reason: z.string().trim().min(1).max(200).default('manual emergency stop') }).strict();
export const ConfirmResetSchema = z.object({ confirm: z.literal('RESET') }).strict();
export const PortfolioResetSchema = z
  .object({ confirm: z.literal('RESET'), startingBalanceSol: finitePositive.max(1_000_000).optional() })
  .strict();

export const PaginationSchema = z.object({
  limit: z.coerce.number().int().min(1).max(500).default(50),
  offset: z.coerce.number().int().min(0).max(1_000_000).default(0),
});

export const BacktestRequestSchema = z
  .object({
    dataset: z.enum(['synthetic', 'recorded']).default('synthetic'),
    seed: z.number().int().min(0).max(2 ** 31 - 1).default(7),
    /** Synthetic only: number of 5s steps to simulate. */
    steps: z.number().int().min(10).max(20_000).default(2_000),
    tokenCount: z.number().int().min(1).max(50).default(12),
    startingBalanceSol: finitePositive.max(1_000_000).default(10),
    /** Recorded only: which provider's snapshots to replay (defaults to the active provider). */
    source: MarketSourceSchema.optional(),
  })
  .strict();

/** Runtime market-data provider selection. Read-only data sources only; has no effect on trading mode. */
export const MarketProviderSelectSchema = z.object({ provider: MarketSourceSchema }).strict();

export type MarketObservation = z.infer<typeof MarketObservationSchema>;
export type MarketSource = z.infer<typeof MarketSourceSchema>;
export type StrategyConfig = z.infer<typeof StrategyConfigSchema>;
export type RiskConfig = z.infer<typeof RiskConfigSchema>;
export type CostConfig = z.infer<typeof CostConfigSchema>;
export type OrderRequest = z.infer<typeof OrderRequestSchema>;
export type BacktestRequest = z.infer<typeof BacktestRequestSchema>;
